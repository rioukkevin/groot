export interface DotPosition {
  x: number;
  y: number;
  active: boolean;
}

export function getTextDots(text: string, spacing = 1): DotPosition[] {
  const dots: DotPosition[] = [];
  const upperText = text.toUpperCase();

  let offsetX = 0;

  for (const char of upperText) {
    const charData = font[char];
    if (!charData) {
      // Unknown character, skip with space width
      offsetX += CHAR_WIDTH + spacing;
      continue;
    }

    for (let row = 0; row < CHAR_HEIGHT; row++) {
      for (let col = 0; col < CHAR_WIDTH; col++) {
        if (charData[row][col] === 1) {
          dots.push({
            x: offsetX + col,
            y: CHAR_HEIGHT - 1 - row, // Flip Y so 0 is bottom
            active: true,
          });
        }
      }
    }

    offsetX += CHAR_WIDTH + spacing;
  }

  // Center the text
  const totalWidth = offsetX - spacing;
  const centerOffsetX = totalWidth / 2;
  const centerOffsetY = CHAR_HEIGHT / 2;

  return dots.map((dot) => ({
    ...dot,
    x: dot.x - centerOffsetX,
    y: dot.y - centerOffsetY,
  }));
}

export { CHAR_WIDTH, CHAR_HEIGHT };
